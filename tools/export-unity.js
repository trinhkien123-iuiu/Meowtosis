// Ghi danh sách level cho Unity: unity/Assets/_Project/Levels/LevelCatalog.txt (định dạng ở docs/architecture.md §5).
// Đọc data/levels.json (đã có par và lời giải), nên chạy sau export-levels.js (npm run export làm cả hai).
// Mỗi level có id cố định lưu ở data/level-ids.json, gắn theo nội dung chơi (rows, goal, oneway, portal, dual, kill):
// đổi thứ tự level không đổi id, sửa lời thoại/mẹo không đổi id; level mới nhận số kế tiếp.
// Sửa nội dung chơi của một level mà muốn giữ tiến độ người chơi: sửa khoá của id đó trong level-ids.json.
//   node tools/export-unity.js
const fs = require('fs');
const path = require('path');
const { LEVELS_JSON } = require('./lib');

const ROOT = path.join(__dirname, '..');
const CATALOG = path.join(ROOT, 'unity/Assets/_Project/Levels/LevelCatalog.txt');
const IDS = path.join(ROOT, 'data/level-ids.json');

// Khoá nội dung chơi của một level, dễ đọc khi mở level-ids.json
function contentKey(level) {
  const parts = [level.rows.join('/')];
  if (level.goal) parts.push('goal ' + level.goal.join('/'));
  if (level.oneway) parts.push('oneway ' + level.oneway.map(m => m.join(',')).join(' '));
  if (level.portal) parts.push('portal ' + level.portal.map(m => m.join(',')).join(' '));
  if (level.dual) parts.push('dual ' + level.dual.map(m => m.join(',')).join(' '));
  if (level.kill) parts.push('kill ' + level.kill);
  return parts.join(' | ');
}

// Gán id cho level chưa có; trả về { ids (id -> khoá), added (số id mới) }
function assignIds(levels, ids) {
  const byKey = new Map(Object.entries(ids).map(([id, key]) => [key, id]));
  let next = Math.max(0, ...Object.keys(ids).map(id => Number(id.split('-')[1]))) + 1;
  const out = { ...ids };
  let added = 0;
  for (const level of levels) {
    const key = contentKey(level);
    if (byKey.has(key)) continue;
    const id = `meow-${String(next++).padStart(3, '0')}`;
    out[id] = key;
    byKey.set(key, id);
    added++;
  }
  return { ids: out, added };
}

// Nội dung LevelCatalog.txt; ném lỗi nếu có level chưa có id
function catalogText(levels, ids) {
  const byKey = new Map(Object.entries(ids).map(([id, key]) => [key, id]));
  const lines = [
    '// Meowtosis level catalog, in play order. Generated by tools/export-unity.js from prototype/meowtosis.html:',
    '// do not edit by hand. Format: docs/architecture.md, section "Level data".',
  ];
  for (const level of levels) {
    const id = byKey.get(contentKey(level));
    if (!id) throw new Error(`level ${level.index} chưa có id: chạy npm run export`);
    lines.push('', `level ${id}`, `block ${level.chapter}`, `par ${level.par}`);
    for (const row of level.rows) lines.push(`row ${row}`);
    for (const row of level.goal || []) lines.push(`goal ${row}`);
    for (const [r, c, dir] of level.oneway || []) lines.push(`membrane ${r} ${c} ${dir}`);
    for (const [r, c, dir, r2, c2] of level.portal || []) lines.push(`portal ${r} ${c} ${dir} ${r2} ${c2}`);
    for (const [r, c, alt, period, left] of level.dual || []) lines.push(`dual ${r} ${c} ${alt} ${period} ${left}`);
    if (level.kill) lines.push(`kill ${level.kill}`);
    if (level.card) lines.push(`card ${level.card}`);
    if (level.trap) lines.push(`trap ${level.trap.join(' ')}`);
    for (const [r, c, dir, text] of level.tut || []) lines.push(`tutorial ${r} ${c} ${dir} ${text}`);
    if (level.tip) lines.push(`tip ${level.tip}`);
    for (const [r, c, dir] of level.solution || []) lines.push(`solution ${r} ${c} ${dir}`);
  }
  return lines.join('\n') + '\n';
}

const readIds = () => { try { return JSON.parse(fs.readFileSync(IDS, 'utf8')); } catch (e) { return {}; } };

if (require.main === module) {
  const levels = JSON.parse(fs.readFileSync(LEVELS_JSON, 'utf8'));
  const { ids, added } = assignIds(levels, readIds());
  fs.writeFileSync(IDS, JSON.stringify(ids, null, 1) + '\n');
  fs.mkdirSync(path.dirname(CATALOG), { recursive: true });
  fs.writeFileSync(CATALOG, catalogText(levels, ids));
  console.log(`Đã ghi ${levels.length} level vào ${path.relative(ROOT, CATALOG)} (${added} id mới)`);
}

module.exports = { CATALOG, IDS, contentKey, catalogText, readIds };
